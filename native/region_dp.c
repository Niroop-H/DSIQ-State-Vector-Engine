/* Bounded subset DP for local binary contraction trees. */
#include <stdint.h>
#include <stddef.h>
#include <math.h>
int dsiq_region_dp(unsigned k,unsigned words,const uint64_t *m,double *cost,uint32_t *split){
 if(k<2||k>16||!words||words>256)return 1;
 uint32_t N=1u<<k;
 for(uint32_t s=1;s<N;s++){
  uint32_t bit=s&-s;if(s==bit){cost[s]=0;split[s]=0;continue;}
  double best=INFINITY;uint32_t pick=0;
  for(uint32_t t=(s-1)&s;t;t=(t-1)&s){
   if(!(t&bit))continue;uint32_t b=s^t;const uint64_t *x=m+(size_t)t*words,*y=m+(size_t)b*words;unsigned r=0;
   for(unsigned j=0;j<words;j++)r+=__builtin_popcountll(x[j]|y[j]);double v=cost[t]+cost[b]+ldexp(1.,r);
   if(v<best){best=v;pick=t;}
  }cost[s]=best;split[s]=pick;
 }return 0;
}
/* DP using arithmetic work for a seven-product matrix multiplication tree.
 * Capped depths, all Strassen additions counted. The table is generated by
 * caller; indexes are logarithms of M,K,N. */
int dsiq_fast_dp(unsigned k,unsigned words,const uint64_t *m,double *cost,uint32_t *split,const double *tab,unsigned dim){
 if(k<2||k>16||!words||words>256||dim>64||dim<2)return 1;
 uint32_t N=1u<<k;unsigned lens[1u<<16];
 for(uint32_t s=1;s<N;s++){unsigned n=0;for(unsigned j=0;j<words;j++)n+=__builtin_popcountll(m[(size_t)s*words+j]);lens[s]=n;}
 for(uint32_t s=1;s<N;s++){
  uint32_t bit=s&-s;if(s==bit){cost[s]=0;split[s]=0;continue;}
  double best=INFINITY;uint32_t pick=0;
  for(uint32_t t=(s-1)&s;t;t=(t-1)&s){
   if(!(t&bit))continue;uint32_t b=s^t;const uint64_t *x=m+(size_t)t*words,*y=m+(size_t)b*words;unsigned inter=0;
   for(unsigned j=0;j<words;j++)inter+=__builtin_popcountll(x[j]&y[j]);
   unsigned M=lens[t]-inter,P=lens[b]-inter,U=lens[t]+lens[b]-inter,K=U-lens[s],B=inter-K;
   double w=(M<dim&&K<dim&&P<dim)?ldexp(tab[(M*dim+K)*dim+P],B):ldexp(1.,U);
   double v=cost[t]+cost[b]+w;if(v<best){best=v;pick=t;}
  }cost[s]=best;split[s]=pick;
 }return 0;
}
